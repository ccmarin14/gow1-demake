def spikes() -> str:
    """Broad silver spikes hugging the medallion ring: four big ones and four small diagonals."""
    out = []
    for deg in range(0, 360, 45):
        a = math.radians(deg)
        big = deg % 90 == 0
        reach, half = (5.0, 4.4) if big else (2.6, 2.6)
        ux, uy = math.cos(a), math.sin(a)
        px, py = -uy, ux
        base = R - 1.2
        p1 = (CX + ux * base + px * half, CY + uy * base + py * half)
        p2 = (CX + ux * base - px * half, CY + uy * base - py * half)
        tip = (CX + ux * (R + reach), CY + uy * (R + reach))
        out.append(f'<path d="M{p1[0]:.1f} {p1[1]:.1f} L{tip[0]:.1f} {tip[1]:.1f} L{p2[0]:.1f} {p2[1]:.1f} Z"/>')
    return "".join(out)


